// hud.cpp — 5x7 bitmap font rendered as cube instances. See hud.h.
#include "hud.h"

namespace {

// Each glyph is 7 rows; the low 5 bits of each row are the pixels, MSB-first
// within those 5 bits (bit 4 is the leftmost column).
struct Glyph
{
    unsigned char rows[7];
};

// clang-format off
const Glyph kDigits[10] = {
    {{0x0E,0x11,0x13,0x15,0x19,0x11,0x0E}}, // 0
    {{0x04,0x0C,0x04,0x04,0x04,0x04,0x0E}}, // 1
    {{0x0E,0x11,0x01,0x02,0x04,0x08,0x1F}}, // 2
    {{0x1F,0x02,0x04,0x02,0x01,0x11,0x0E}}, // 3
    {{0x02,0x06,0x0A,0x12,0x1F,0x02,0x02}}, // 4
    {{0x1F,0x10,0x1E,0x01,0x01,0x11,0x0E}}, // 5
    {{0x06,0x08,0x10,0x1E,0x11,0x11,0x0E}}, // 6
    {{0x1F,0x01,0x02,0x04,0x08,0x08,0x08}}, // 7
    {{0x0E,0x11,0x11,0x0E,0x11,0x11,0x0E}}, // 8
    {{0x0E,0x11,0x11,0x0F,0x01,0x02,0x0C}}, // 9
};

const Glyph kLetters[26] = {
    {{0x0E,0x11,0x11,0x1F,0x11,0x11,0x11}}, // A
    {{0x1E,0x11,0x11,0x1E,0x11,0x11,0x1E}}, // B
    {{0x0E,0x11,0x10,0x10,0x10,0x11,0x0E}}, // C
    {{0x1C,0x12,0x11,0x11,0x11,0x12,0x1C}}, // D
    {{0x1F,0x10,0x10,0x1E,0x10,0x10,0x1F}}, // E
    {{0x1F,0x10,0x10,0x1E,0x10,0x10,0x10}}, // F
    {{0x0E,0x11,0x10,0x17,0x11,0x11,0x0F}}, // G
    {{0x11,0x11,0x11,0x1F,0x11,0x11,0x11}}, // H
    {{0x0E,0x04,0x04,0x04,0x04,0x04,0x0E}}, // I
    {{0x07,0x02,0x02,0x02,0x02,0x12,0x0C}}, // J
    {{0x11,0x12,0x14,0x18,0x14,0x12,0x11}}, // K
    {{0x10,0x10,0x10,0x10,0x10,0x10,0x1F}}, // L
    {{0x11,0x1B,0x15,0x15,0x11,0x11,0x11}}, // M
    {{0x11,0x11,0x19,0x15,0x13,0x11,0x11}}, // N
    {{0x0E,0x11,0x11,0x11,0x11,0x11,0x0E}}, // O
    {{0x1E,0x11,0x11,0x1E,0x10,0x10,0x10}}, // P
    {{0x0E,0x11,0x11,0x11,0x15,0x12,0x0D}}, // Q
    {{0x1E,0x11,0x11,0x1E,0x14,0x12,0x11}}, // R
    {{0x0F,0x10,0x10,0x0E,0x01,0x01,0x1E}}, // S
    {{0x1F,0x04,0x04,0x04,0x04,0x04,0x04}}, // T
    {{0x11,0x11,0x11,0x11,0x11,0x11,0x0E}}, // U
    {{0x11,0x11,0x11,0x11,0x11,0x0A,0x04}}, // V
    {{0x11,0x11,0x11,0x15,0x15,0x1B,0x11}}, // W
    {{0x11,0x11,0x0A,0x04,0x0A,0x11,0x11}}, // X
    {{0x11,0x11,0x0A,0x04,0x04,0x04,0x04}}, // Y
    {{0x1F,0x01,0x02,0x04,0x08,0x10,0x1F}}, // Z
};

const Glyph kPeriod  = {{0x00,0x00,0x00,0x00,0x00,0x0C,0x0C}};
const Glyph kColon   = {{0x00,0x0C,0x0C,0x00,0x0C,0x0C,0x00}};
const Glyph kPercent = {{0x18,0x19,0x02,0x04,0x08,0x13,0x03}};
const Glyph kSlash   = {{0x01,0x02,0x02,0x04,0x08,0x08,0x10}};
const Glyph kDash    = {{0x00,0x00,0x00,0x1F,0x00,0x00,0x00}};
const Glyph kBlank   = {{0x00,0x00,0x00,0x00,0x00,0x00,0x00}};
// clang-format on

const Glyph& glyphFor(char c)
{
    if (c >= '0' && c <= '9') return kDigits[c - '0'];
    if (c >= 'A' && c <= 'Z') return kLetters[c - 'A'];
    if (c >= 'a' && c <= 'z') return kLetters[c - 'a'];
    switch (c)
    {
        case '.': return kPeriod;
        case ':': return kColon;
        case '%': return kPercent;
        case '/': return kSlash;
        case '-': return kDash;
        default:  return kBlank;
    }
}

} // namespace

int Hud_AppendText(RenderItem* items, int count, int maxItems, const float origin[3],
                   const float right[3], const float up[3], const float forward[3],
                   float pixelSize, const float color[3], const char* text)
{
    if (text == nullptr)
    {
        return count;
    }

    // Slightly under half a pixel, so adjacent lit pixels read as separate dots
    // rather than fusing into an unreadable slab.
    const float h = pixelSize * 0.4f;

    for (int ci = 0; text[ci] != '\0'; ++ci)
    {
        const Glyph& g = glyphFor(text[ci]);
        const float  advance = static_cast<float>(ci) * 6.0f * pixelSize;

        for (int row = 0; row < 7; ++row)
        {
            const unsigned char bits = g.rows[row];
            for (int col = 0; col < 5; ++col)
            {
                if ((bits & (1u << (4 - col))) == 0)
                {
                    continue;
                }
                if (count >= maxItems)
                {
                    return count; // out of instance budget; drop the rest silently
                }

                const float x = advance + static_cast<float>(col) * pixelSize;
                const float y = -static_cast<float>(row) * pixelSize;

                RenderItem& it = items[count];

                // Columns are the text-plane basis scaled to the dot size, so each
                // dot is a small cube lying in the plane of the text.
                it.model[0]  = right[0] * h;
                it.model[1]  = right[1] * h;
                it.model[2]  = right[2] * h;
                it.model[3]  = 0.0f;

                it.model[4]  = up[0] * h;
                it.model[5]  = up[1] * h;
                it.model[6]  = up[2] * h;
                it.model[7]  = 0.0f;

                it.model[8]  = forward[0] * h;
                it.model[9]  = forward[1] * h;
                it.model[10] = forward[2] * h;
                it.model[11] = 0.0f;

                it.model[12] = origin[0] + right[0] * x + up[0] * y;
                it.model[13] = origin[1] + right[1] * x + up[1] * y;
                it.model[14] = origin[2] + right[2] * x + up[2] * y;
                it.model[15] = 1.0f;

                it.color[0] = color[0];
                it.color[1] = color[1];
                it.color[2] = color[2];
                it.color[3] = 1.0f;

                ++count;
            }
        }
    }

    return count;
}
